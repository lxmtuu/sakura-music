// Run with CHROMIUM_PATH=/path/to/chromium npm run test:browser.
// All data lives in an isolated temporary directory.
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const { spawn } = require('node:child_process');

async function main() {
  if (!process.env.CHROMIUM_PATH) throw new Error('Set CHROMIUM_PATH to a Chromium or Chrome executable.');
  const root = path.resolve(__dirname, '..');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sakura-browser-'));
  fs.copyFileSync(path.join(root, 'server.js'), path.join(dir, 'server.js'));
  fs.cpSync(path.join(root, 'lib'), path.join(dir, 'lib'), { recursive: true });
  fs.symlinkSync(path.join(root, 'node_modules'), path.join(dir, 'node_modules'), 'dir');
  fs.symlinkSync(path.join(root, 'public'), path.join(dir, 'public'), 'dir');
  const sock = net.createServer(); await new Promise((r) => sock.listen(0, '127.0.0.1', r));
  const port = sock.address().port; await new Promise((r) => sock.close(r));
  const base = `http://127.0.0.1:${port}`;
  const server = spawn(process.execPath, [path.join(dir, 'server.js')], { env: { ...process.env, PORT: String(port), ADMIN_PASSWORD: 'secure-test-password', SECRET: 'test-secret', NODE_ENV: 'test', DEMO_MODE: '0' }, stdio: 'ignore' });
  let browser;
  try {
    for (let i = 0; i < 100; i++) { try { if ((await fetch(base + '/api/health')).ok) break; } catch {} await new Promise(r => setTimeout(r, 50)); }
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true, args: ['--no-sandbox'] });
    const errors = [];
    const context = await browser.newContext({ viewport: { width: 1280, height: 800 } });
    await context.route('**/*', route => route.request().url().startsWith(base) || route.request().url().startsWith('data:') ? route.continue() : route.abort());
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/register.html?redirect=products.html');
    await page.fill('[name=name]', 'Khách thử nghiệm');
    await page.fill('[name=email]', 'khach@example.com');
    await page.fill('[name=phone]', '0900000000');
    await page.fill('[name=address]', '123 Đường Hoa');
    await page.fill('[name=password]', 'password123');
    await page.click('#regForm button[type=submit]');
    await page.waitForURL('**/products.html');
    await page.locator('#grid .product-card').first().waitFor();
    await page.locator('#grid .product-card').first().locator('button').click();
    await page.goto(base + '/cart.html');
    await page.locator('.cart-table tbody tr').first().waitFor();
    await page.locator('a[href="checkout.html"]').last().click();
    await page.locator('#checkoutForm').waitFor();
    const unsupported = await context.newPage();
    await unsupported.addInitScript(() => Object.defineProperty(navigator, 'locks', { value: undefined, configurable: true }));
    await unsupported.goto(base + '/checkout.html');
    await unsupported.locator('#checkoutForm').waitFor();
    await unsupported.locator('#checkoutForm button[type=submit]').click();
    await unsupported.getByText('Trình duyệt không hỗ trợ khóa thanh toán an toàn').waitFor();
    assert.equal((await unsupported.evaluate(async () => (await (await fetch('/api/orders/me')).json()).orders)).length, 0);
    await unsupported.close();
    const staleTab = await context.newPage();
    staleTab.on('pageerror', error => errors.push(error.message));
    await staleTab.goto(base + '/checkout.html');
    await staleTab.locator('#checkoutForm').waitFor();
    // Simulate a dropped response after the server has committed the order.
    let lostOrder;
    let notifyCommitted, allowResponse;
    const committed = new Promise(resolve => { notifyCommitted = resolve; });
    const responseAllowed = new Promise(resolve => { allowResponse = resolve; });
    const dropResponse = async (route) => {
      const response = await route.fetch();
      assert.equal(response.status(), 201);
      lostOrder = (await response.json()).order;
      notifyCommitted();
      await responseAllowed;
      await route.abort('failed');
    };
    await page.route('**/api/orders', dropResponse);
    await page.locator('#checkoutForm button[type=submit]').click();
    await committed;
    await staleTab.locator('#checkoutForm button[type=submit]').click();
    await staleTab.getByText('Một yêu cầu đặt hàng đang được xử lý ở tab khác').waitFor();
    allowResponse();
    await page.getByText('Đơn hàng trước chưa rõ kết quả').waitFor();
    await page.unroute('**/api/orders', dropResponse);
    const inventoryAfterCreate = (await (await fetch(base + '/api/products/' + lostOrder.items[0].productId)).json()).product.stock;
    const retryTab = await context.newPage();
    retryTab.on('pageerror', error => errors.push(error.message));
    await retryTab.goto(base + '/checkout.html');
    await retryTab.getByText('Đơn hàng trước chưa rõ kết quả').waitFor();
    await page.reload();
    await page.getByText('Đơn hàng trước chưa rõ kết quả').waitFor();
    await page.getByRole('button', { name: 'Kiểm tra / tiếp tục đơn cũ' }).click();
    await page.getByText('Đặt hàng thành công!').waitFor();
    assert.ok((await page.locator('#checkoutRoot').innerText()).includes(lostOrder.code));
    await retryTab.getByRole('button', { name: 'Kiểm tra / tiếp tục đơn cũ' }).click();
    await retryTab.getByText('Yêu cầu cũ đã được xử lý ở tab khác').waitFor();
    await staleTab.locator('#checkoutForm button[type=submit]').click();
    await staleTab.getByText('Giỏ hàng đã thay đổi ở tab khác').waitFor();
    await retryTab.close(); await staleTab.close();
    const customerOrders = await page.evaluate(async () => (await (await fetch('/api/orders/me')).json()).orders);
    assert.equal(customerOrders.length, 1);
    assert.equal(customerOrders[0].id, lostOrder.id);
    assert.equal((await (await fetch(base + '/api/products/' + lostOrder.items[0].productId)).json()).product.stock, inventoryAfterCreate);
    await page.getByRole('button', { name: 'Tôi đã chuyển khoản' }).click();
    await page.waitForURL('**/account.html');
    await page.getByText('Chờ shop xác nhận CK').waitFor();

    const adminContext = await browser.newContext({ viewport: { width: 1280, height: 800 } });
    await adminContext.route('**/*', route => route.request().url().startsWith(base) || route.request().url().startsWith('data:') ? route.continue() : route.abort());
    const admin = await adminContext.newPage();
    admin.on('pageerror', error => errors.push(error.message));
    await admin.goto(base + '/admin-login.html');
    await admin.fill('[name=password]', 'secure-test-password');
    await admin.click('#adminLoginForm button[type=submit]');
    await admin.waitForURL('**/admin.html');
    await admin.locator('#backupStatus').getByText('Thành công gần nhất').waitFor();
    await admin.locator('#emailStatus').getByText('SMTP chưa được cấu hình').waitFor();
    await admin.locator('#proxyStatus').getByText('Chưa tin proxy nào').waitFor();
    await admin.locator('#refreshBackup').click();
    const backupError = route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ backup: { enabled: true, lastAttemptFailed: true, lastSuccess: null } }) });
    await admin.route('**/api/admin/system', backupError);
    await admin.locator('#refreshBackup').click();
    await admin.locator('#backupStatus').getByText('Lần sao lưu gần nhất thất bại').waitFor();
    await admin.unroute('**/api/admin/system', backupError);
    await admin.locator('#refreshBackup').click();
    await admin.locator('#backupStatus').getByText('Thành công gần nhất').waitFor();
    await admin.locator('#ordersBody tr').first().waitFor({ state: 'attached' });
    await admin.locator('[data-view=orders]').click();
    await admin.locator('#ordersBody button').first().click();
    await admin.selectOption('#statusSel', 'paid');
    await admin.getByRole('button', { name: 'Lưu trạng thái' }).click();
    await admin.locator('#modalMask').waitFor({ state: 'hidden' });
    await page.reload();
    await page.getByText('Đã thanh toán').waitFor();
    await admin.locator('[data-view=users]').click();
    await admin.locator('#usersBody').getByText('khach@example.com').waitFor();
    await admin.locator('[data-view=products]').click();
    await admin.getByRole('button', { name: 'Thêm sản phẩm' }).click();
    await admin.locator('#productForm [name=name]').fill('Sản phẩm kiểm thử');
    await admin.locator('#productForm [name=price]').fill('123000');
    await admin.locator('#productForm [name=stock]').fill('2');
    await admin.locator('#productForm button[type=submit]').click();
    await admin.locator('#modalMask').waitFor({ state: 'hidden' });
    await admin.locator('#productsBody').getByText('Sản phẩm kiểm thử').waitFor();

    // A slower filter response must never replace a newer selection.
    const filters = await browser.newPage({ viewport: { width: 1280, height: 800 } });
    await filters.goto(base + '/products.html');
    await filters.locator('#catFilter button').first().waitFor();
    let releaseOld, oldStarted;
    const oldBlocked = new Promise(resolve => { releaseOld = resolve; });
    const oldSeen = new Promise(resolve => { oldStarted = resolve; });
    await filters.route('**/api/products?*', async route => {
      const url = new URL(route.request().url());
      if (url.searchParams.get('category') === 'Guitar') { oldStarted(); await oldBlocked; }
      await route.continue();
    });
    await filters.locator('#catFilter button[data-cat="Guitar"]').click();
    await oldSeen;
    await filters.locator('#catFilter button[data-cat="Piano & Keyboard"]').click();
    await filters.locator('#catFilter button[data-cat="Piano & Keyboard"][aria-pressed=true]').waitFor();
    releaseOld();
    await filters.waitForTimeout(150);
    assert.equal(await filters.locator('#crumbCat').textContent(), 'Piano & Keyboard');
    await filters.selectOption('#sortSel', 'price-desc');
    await filters.locator('#resetBtn').click();
    assert.equal(await filters.locator('#sortSel').inputValue(), 'rating');
    await filters.close();

    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    await mobile.route('**/*', route => route.request().url().startsWith(base) || route.request().url().startsWith('data:') ? route.continue() : route.abort());
    const phone = await mobile.newPage();
    phone.on('pageerror', error => errors.push(error.message));
    await phone.goto(base + '/products.html');
    await phone.locator('.menu-toggle').click();
    assert.equal(await phone.locator('.menu-toggle').getAttribute('aria-expanded'), 'true');
    await phone.keyboard.press('Escape');
    assert.equal(await phone.locator('.menu-toggle').getAttribute('aria-expanded'), 'false');
    await phone.locator('.menu-toggle').click();
    await phone.locator('.mobile-search input').fill('Yamaha');
    await phone.locator('.mobile-search input').press('Enter');
    await phone.waitForURL('**/products.html?q=Yamaha');
    await phone.locator('#grid .product-card').first().waitFor();
    const productOverflow = await phone.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: document.documentElement.clientWidth }));
    assert.ok(productOverflow.width <= productOverflow.viewport + 1, `mobile products overflow: ${JSON.stringify(productOverflow)}`);
    await phone.locator('#grid .product-card').first().locator('button').click();
    await phone.goto(base + '/cart.html');
    await phone.locator('.cart-table tbody tr').first().waitFor();
    const otherCart = await mobile.newPage();
    await otherCart.goto(base + '/products.html');
    await otherCart.locator('#grid .product-card').first().waitFor();
    const itemId = await phone.evaluate(() => JSON.parse(localStorage.getItem('sakura_cart_v1'))[0].id);
    await otherCart.evaluate(id => { const items = JSON.parse(localStorage.getItem('sakura_cart_v1')); items[0].qty = 2; localStorage.setItem('sakura_cart_v1', JSON.stringify(items)); }, itemId);
    await phone.locator('.qty-stepper input[value="2"]').waitFor();
    await otherCart.evaluate(() => { const items = JSON.parse(localStorage.getItem('sakura_cart_v1')); items[0].qty = 1; localStorage.setItem('sakura_cart_v1', JSON.stringify(items)); });
    await phone.locator('.qty-stepper input[value="1"]').waitFor();
    await otherCart.close();
    await phone.locator('a[href="checkout.html"]').last().click();
    await phone.getByRole('link', { name: 'Đăng nhập', exact: true }).click();
    await phone.fill('[name=email]', 'khach@example.com');
    await phone.fill('[name=password]', 'password123');
    await phone.click('#loginForm button[type=submit]');
    await phone.waitForURL('**/checkout.html');
    await phone.locator('#checkoutForm').waitFor();
    const productId = await phone.evaluate(() => JSON.parse(localStorage.getItem('sakura_cart_v1'))[0].id);
    const product = await (await fetch(base + '/api/products/' + productId)).json();
    const updatePrice = async (price) => admin.evaluate(async ({ productId, price }) => {
      const response = await fetch('/api/admin/products/' + productId, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ price }) });
      return response.status;
    }, { productId, price });
    assert.equal(await updatePrice(product.product.price + 1000), 200);
    await phone.locator('#checkoutForm button[type=submit]').click();
    await phone.getByText('Giá sản phẩm đã thay đổi').waitFor();
    assert.equal(await updatePrice(product.product.price), 200);
    await phone.reload();
    await phone.locator('[data-method=cod]').click();
    await phone.locator('#checkoutForm button[type=submit]').click();
    await phone.getByText('Đặt hàng thành công!').waitFor();
    await phone.setViewportSize({ width: 320, height: 720 });
    await phone.goto(base + '/cart.html');
    await phone.locator('.user-chip').waitFor();
    await phone.getByText('Giỏ hàng của bạn đang trống').waitFor();
    const overflow = await phone.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: document.documentElement.clientWidth }));
    assert.ok(overflow.width <= overflow.viewport + 1, `mobile cart overflows: ${JSON.stringify(overflow)}`);
    await phone.evaluate(() => localStorage.setItem('sakura_cart_v1', JSON.stringify([{ id: 'p99', qty: 1 }])));
    await phone.goto(base + '/cart.html');
    await phone.getByText('Sản phẩm không còn bán (p99)', { exact: true }).waitFor();
    await phone.locator('.cart-table button[title=Xóa]').click();
    await phone.getByText('Giỏ hàng của bạn đang trống').waitFor();
    await phone.goto(base + '/forgot-password.html');
    await phone.fill('#step1 [name=email]', 'khach@example.com');
    await phone.locator('#step1 button[type=submit]').click();
    await phone.getByText('Chức năng khôi phục mật khẩu chưa được cấu hình').waitFor();
    assert.ok(await phone.locator('#step1').isVisible());
    assert.equal(await phone.evaluate(() => safeRedirect('https://example.com/phishing')), 'index.html');
    assert.equal(await phone.evaluate(() => safeRedirect('checkout.html')), '/checkout.html');
    // A login in another tab must not submit the old checkout as a different account.
    await phone.goto(base + '/products.html');
    await phone.locator('#grid .product-card').first().waitFor();
    await phone.locator('#grid .product-card').first().locator('button').click();
    await phone.goto(base + '/checkout.html');
    await phone.locator('#checkoutForm').waitFor();
    const switchAccount = (email, password) => phone.evaluate(async ({ email, password }) => {
      const res = await fetch('/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email, password }) });
      return res.status;
    }, { email, password });
    assert.equal(await switchAccount('admin@sakura.vn', 'secure-test-password'), 200);
    await phone.locator('#checkoutForm button[type=submit]').click();
    await phone.getByText('Tài khoản đăng nhập đã thay đổi').waitFor();
    assert.equal((await phone.evaluate(async () => (await (await fetch('/api/orders/me')).json()).orders)).length, 0);
    assert.equal(await switchAccount('khach@example.com', 'password123'), 200);
    await phone.reload();
    await phone.getByRole('button', { name: 'Kiểm tra / tiếp tục đơn cũ' }).click();
    await phone.getByText('Đặt hàng thành công!').waitFor();
    assert.deepEqual(errors, [], `browser errors: ${errors.join('; ')}`);
    console.log('Browser flows passed: registration, login, QR and COD orders, lost response recovery, multiple tabs, account switch, stale price, admin order and product management, account, mobile search and cart.');
  } finally {
    if (browser) await browser.close();
    server.kill();
    fs.rmSync(dir, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
